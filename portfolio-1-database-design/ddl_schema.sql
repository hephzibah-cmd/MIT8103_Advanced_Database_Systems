CASCADE;

-- 1. Currencies Master Table
CREATE TABLE currencies (
    currency_code CHAR(3) PRIMARY KEY,
    currency_name VARCHAR(50) NOT NULL,
    currency_symbol VARCHAR(5) NOT NULL,
    decimal_places INTEGER NOT NULL DEFAULT 2
        CHECK (decimal_places BETWEEN 0 AND 4),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Account Types Master Table
CREATE TABLE account_types (
    account_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR(50) NOT NULL UNIQUE,
    minimum_balance NUMERIC(18, 4) NOT NULL DEFAULT 0.0000
        CHECK (minimum_balance >= 0.0000),
    interest_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.0000
        CHECK (interest_rate >= 0.0000),
    default_overdraft_limit NUMERIC(18, 4) NOT NULL DEFAULT 0.0000
        CHECK (default_overdraft_limit >= 0.0000)
);

-- 3. Customers Entity Table
CREATE TABLE customers (
    customer_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    tier_level VARCHAR(20) NOT NULL DEFAULT 'TIER_1'
        CHECK (tier_level IN ('TIER_1', 'TIER_2', 'TIER_3')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. KYC Verifications Compliance Table
CREATE TABLE kyc_verifications (
    kyc_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID NOT NULL,
    document_type VARCHAR(30) NOT NULL
        CHECK (document_type IN ('NATIONAL_ID', 'PASSPORT', 'DRIVERS_LICENSE', 'BVN')),
    id_number VARCHAR(64) NOT NULL,
    verification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    verified_by VARCHAR(50),
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_kyc_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id) ON DELETE RESTRICT,
    CONSTRAINT uq_kyc_document UNIQUE (document_type, id_number),
    CONSTRAINT chk_kyc_pending_has_no_verified_at CHECK (
        verification_status <> 'PENDING' OR verified_at IS NULL
    ),
    CONSTRAINT chk_kyc_verified_has_timestamp CHECK (
        verification_status <> 'VERIFIED' OR verified_at IS NOT NULL
    )
);

-- 5. Accounts Financial Entity Table
CREATE TABLE accounts (
    account_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID NOT NULL,
    account_type_id INTEGER NOT NULL,
    currency_code CHAR(3) NOT NULL,
    account_number VARCHAR(20) NOT NULL UNIQUE,
    current_balance NUMERIC(18, 4) NOT NULL DEFAULT 0.0000,
    hold_balance NUMERIC(18, 4) NOT NULL DEFAULT 0.0000,
    overdraft_limit NUMERIC(18, 4) NOT NULL DEFAULT 0.0000,
    version INTEGER NOT NULL DEFAULT 1,
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'DORMANT', 'FROZEN', 'CLOSED')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounts_type FOREIGN KEY (account_type_id)
        REFERENCES account_types (account_type_id) ON DELETE RESTRICT,
    CONSTRAINT fk_accounts_currency FOREIGN KEY (currency_code)
        REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT chk_account_solvency CHECK (current_balance >= -overdraft_limit),
    CONSTRAINT chk_account_holds CHECK (
        hold_balance >= 0.0000
        AND hold_balance <= (current_balance + overdraft_limit)
    ),
    CONSTRAINT chk_account_overdraft CHECK (overdraft_limit >= 0.0000),
    CONSTRAINT chk_account_closed_at CHECK (
        (account_status = 'CLOSED') = (closed_at IS NOT NULL)
    )
);

-- 6. Merchants Business Entity Table
CREATE TABLE merchants (
    merchant_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    settlement_account_id UUID NOT NULL UNIQUE,
    business_name VARCHAR(100) NOT NULL,
    registration_number VARCHAR(50) NOT NULL UNIQUE,
    merchant_category_code VARCHAR(10) NOT NULL,
    commission_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.0150
        CHECK (commission_rate BETWEEN 0.0000 AND 0.1000),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_merchants_account FOREIGN KEY (settlement_account_id)
        REFERENCES accounts (account_id) ON DELETE RESTRICT
);

-- 7. Journal Entries (Double-Entry Header Table, append-only)
CREATE TABLE journal_entries (
    journal_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    entry_reference VARCHAR(64) NOT NULL UNIQUE,
    narrative VARCHAR(255) NOT NULL,
    event_type VARCHAR(30) NOT NULL
        CHECK (event_type IN (
            'P2P_TRANSFER',
            'CARD_PAYMENT',
            'MERCHANT_SETTLEMENT',
            'FEE_CHARGE',
            'DEPOSIT',
            'WITHDRAWAL',
            'REVERSAL'
        )),
    posting_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 8. Ledger Entries (Double-Entry Line Items Table, append-only)
CREATE TABLE ledger_entries (
    ledger_entry_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    journal_id UUID NOT NULL,
    account_id UUID NOT NULL,
    entry_type VARCHAR(6) NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount NUMERIC(18, 4) NOT NULL CHECK (amount > 0.0000),
    balance_after NUMERIC(18, 4) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ledger_journal FOREIGN KEY (journal_id)
        REFERENCES journal_entries (journal_id) ON DELETE RESTRICT,
    CONSTRAINT fk_ledger_account FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE RESTRICT
);

-- 9. Transactions Customer-Facing Payment Processing Table
CREATE TABLE transactions (
    transaction_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    transaction_reference VARCHAR(64) NOT NULL UNIQUE,
    idempotency_key VARCHAR(128) NOT NULL UNIQUE,
    source_account_id UUID,
    destination_account_id UUID,
    merchant_id UUID,
    journal_id UUID UNIQUE,
    currency_code CHAR(3) NOT NULL,
    amount NUMERIC(18, 4) NOT NULL CHECK (amount > 0.0000),
    fee_amount NUMERIC(18, 4) NOT NULL DEFAULT 0.0000
        CHECK (fee_amount >= 0.0000),
    channel VARCHAR(20) NOT NULL
        CHECK (channel IN ('MOBILE_APP', 'WEB_PORTAL', 'POS_TERMINAL', 'API_INTEGRATION')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'SETTLED', 'FAILED', 'REVERSED')),
    initiated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT fk_txn_source FOREIGN KEY (source_account_id)
        REFERENCES accounts (account_id) ON DELETE RESTRICT,
    CONSTRAINT fk_txn_destination FOREIGN KEY (destination_account_id)
        REFERENCES accounts (account_id) ON DELETE RESTRICT,
    CONSTRAINT fk_txn_merchant FOREIGN KEY (merchant_id)
        REFERENCES merchants (merchant_id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_journal FOREIGN KEY (journal_id)
        REFERENCES journal_entries (journal_id) ON DELETE SET NULL,
    CONSTRAINT fk_txn_currency FOREIGN KEY (currency_code)
        REFERENCES currencies (currency_code) ON DELETE RESTRICT,
    CONSTRAINT chk_txn_party_present CHECK (
        source_account_id IS NOT NULL
        OR destination_account_id IS NOT NULL
        OR merchant_id IS NOT NULL
    ),
    CONSTRAINT chk_no_self_transfer CHECK (
        source_account_id IS NULL
        OR destination_account_id IS NULL
        OR source_account_id <> destination_account_id
    ),
    CONSTRAINT chk_txn_completed_at CHECK (
        (status = 'PENDING') = (completed_at IS NULL)
    )
);

-- 10. Cards Entity Table (PCI DSS aligned: no CVV / PIN storage)
CREATE TABLE cards (
    card_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id UUID NOT NULL,
    masked_pan VARCHAR(20) NOT NULL,
    card_token VARCHAR(128) NOT NULL UNIQUE,
    pan_hmac CHAR(64) NOT NULL UNIQUE,
    expiry_date DATE NOT NULL,
    card_type VARCHAR(20) NOT NULL DEFAULT 'DEBIT'
        CHECK (card_type IN ('DEBIT', 'VIRTUAL_DEBIT', 'PREPAID')),
    daily_spend_limit NUMERIC(18, 4) NOT NULL DEFAULT 5000.0000
        CHECK (daily_spend_limit >= 0.0000),
    card_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (card_status IN ('ACTIVE', 'FROZEN', 'BLOCKED', 'EXPIRED')),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cards_account FOREIGN KEY (account_id)
        REFERENCES accounts (account_id) ON DELETE RESTRICT,
    CONSTRAINT chk_masked_pan_not_full CHECK (
        length(regexp_replace(masked_pan, '[^0-9]', '', 'g')) <= 10
    ),
    CONSTRAINT chk_pan_hmac_format CHECK (pan_hmac ~ '^[0-9a-f]{64}$')
);

COMMENT ON TABLE cards IS
    'PCI DSS scope: CVV/CVC and PIN are never stored. The full PAN is held only in the external token vault.';
COMMENT ON COLUMN cards.masked_pan IS
    'Truncated PAN showing at most the first 6 and last 4 digits (PCI DSS 3.3.1).';
COMMENT ON COLUMN cards.card_token IS
    'Opaque token returned by the PCI-scoped card vault; usable instead of the PAN.';
COMMENT ON COLUMN cards.pan_hmac IS
    'Keyed HMAC-SHA-256 fingerprint of the PAN using a KMS/HSM-held key (PCI DSS 3.5.1.2), not a plain hash.';

