-- 1. Financial history is append-only: no UPDATE or DELETE on ledger headers/lines.
CREATE OR REPLACE FUNCTION reject_financial_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        '% on % is not permitted: financial history is append-only',
        TG_OP, TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER trg_journal_append_only
BEFORE UPDATE OR DELETE ON journal_entries
FOR EACH ROW EXECUTE FUNCTION reject_financial_mutation();

CREATE TRIGGER trg_ledger_append_only
BEFORE UPDATE OR DELETE ON ledger_entries
FOR EACH ROW EXECUTE FUNCTION reject_financial_mutation();

-- 2. Deferred constraint: every journal must have at least two lines and
--    sum(DEBIT) = sum(CREDIT) by the end of the transaction.
CREATE OR REPLACE FUNCTION assert_journal_balanced()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_journal_id UUID;
    v_lines INTEGER;
    v_debits NUMERIC(18, 4);
    v_credits NUMERIC(18, 4);
BEGIN
    IF TG_TABLE_NAME = 'journal_entries' THEN
        v_journal_id := NEW.journal_id;
    ELSIF TG_OP = 'DELETE' THEN
        v_journal_id := OLD.journal_id;
    ELSE
        v_journal_id := NEW.journal_id;
    END IF;

    SELECT
        COUNT(*),
        COALESCE(SUM(CASE WHEN entry_type = 'DEBIT' THEN amount ELSE 0 END), 0),
        COALESCE(SUM(CASE WHEN entry_type = 'CREDIT' THEN amount ELSE 0 END), 0)
    INTO v_lines, v_debits, v_credits
    FROM ledger_entries
    WHERE journal_id = v_journal_id;

    IF v_lines < 2 THEN
        RAISE EXCEPTION
            'Journal % must contain at least two ledger lines', v_journal_id;
    END IF;

    IF v_debits <> v_credits THEN
        RAISE EXCEPTION
            'Journal % is unbalanced: debits % <> credits %',
            v_journal_id, v_debits, v_credits;
    END IF;

    RETURN NULL;
END;
$$;

-- Check each line set at commit time, not per row.
CREATE CONSTRAINT TRIGGER trg_ledger_balanced
AFTER INSERT OR UPDATE OR DELETE ON ledger_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_journal_balanced();

-- Also reject journals that are committed without any ledger lines.
CREATE CONSTRAINT TRIGGER trg_journal_has_lines
AFTER INSERT ON journal_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_journal_balanced();

-- 3. Apply each ledger posting to the account balance and verify balance_after.
--    This makes the account balance a posting-maintained value rather than a
--    manually edited field.
CREATE OR REPLACE FUNCTION apply_ledger_posting()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_balance NUMERIC(18, 4);
BEGIN
    IF NEW.entry_type = 'DEBIT' THEN
        UPDATE accounts
        SET current_balance = current_balance - NEW.amount
        WHERE account_id = NEW.account_id
        RETURNING current_balance INTO v_balance;
    ELSE
        UPDATE accounts
        SET current_balance = current_balance + NEW.amount
        WHERE account_id = NEW.account_id
        RETURNING current_balance INTO v_balance;
    END IF;

    IF v_balance IS NULL THEN
        RAISE EXCEPTION 'Account % does not exist', NEW.account_id;
    END IF;

    IF v_balance <> NEW.balance_after THEN
        RAISE EXCEPTION
            'balance_after mismatch for account %: expected %, supplied %',
            NEW.account_id, v_balance, NEW.balance_after;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ledger_apply_balance
AFTER INSERT ON ledger_entries
FOR EACH ROW EXECUTE FUNCTION apply_ledger_posting();

-- 4. Ensure a transaction's currency matches every linked account.
CREATE OR REPLACE FUNCTION assert_transaction_currency()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_currency CHAR(3);
BEGIN
    IF NEW.source_account_id IS NOT NULL THEN
        SELECT currency_code INTO v_currency
        FROM accounts WHERE account_id = NEW.source_account_id;
        IF v_currency IS NOT NULL AND v_currency <> NEW.currency_code THEN
            RAISE EXCEPTION
                'Transaction currency % does not match source account currency %',
                NEW.currency_code, v_currency;
        END IF;
    END IF;

    IF NEW.destination_account_id IS NOT NULL THEN
        SELECT currency_code INTO v_currency
        FROM accounts WHERE account_id = NEW.destination_account_id;
        IF v_currency IS NOT NULL AND v_currency <> NEW.currency_code THEN
            RAISE EXCEPTION
                'Transaction currency % does not match destination account currency %',
                NEW.currency_code, v_currency;
        END IF;
    END IF;

    IF NEW.merchant_id IS NOT NULL THEN
        SELECT a.currency_code INTO v_currency
        FROM merchants m
        JOIN accounts a ON a.account_id = m.settlement_account_id
        WHERE m.merchant_id = NEW.merchant_id;
        IF v_currency IS NOT NULL AND v_currency <> NEW.currency_code THEN
            RAISE EXCEPTION
                'Transaction currency % does not match merchant settlement currency %',
                NEW.currency_code, v_currency;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_transaction_currency_guard
BEFORE INSERT OR UPDATE OF
    source_account_id,
    destination_account_id,
    merchant_id,
    currency_code
ON transactions
FOR EACH ROW EXECUTE FUNCTION assert_transaction_currency();

-- 5. Maintain customers.updated_at automatically.
CREATE OR REPLACE FUNCTION set_customer_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_customers_updated_at
BEFORE UPDATE ON customers
FOR EACH ROW EXECUTE FUNCTION set_customer_updated_at();
